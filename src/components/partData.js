function isPointInPolygon(point, polygon) {
  const x = point.x;
  const y = point.y;
  let isInside = false;

  // 遍历多边形的每一条边
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i].x,
      yi = polygon[i].y;
    const xj = polygon[j].x,
      yj = polygon[j].y;

    // 核心判断逻辑
    // 1. 检查点的 Y 坐标是否在当前边的 Y 坐标范围内
    // 2. 检查点是否在从该点发出的水平射线的左侧
    const intersect =
      yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;

    if (intersect) {
      isInside = !isInside;
    }
  }

  return isInside;
}

